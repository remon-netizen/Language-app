// Deduplicate on the Ukrainian form (a word may be listed under one theme only).
const seen = new Set();
const unique = R.filter(r => (seen.has(r[0]) ? false : seen.add(r[0])));

// Within a theme the rows run from most to least frequent. `rank` is a word's
// relative position inside its theme, and the deck is sorted on it, so "Learn 10
// new" over all themes deals from every theme at once: each batch holds a couple
// of verbs, a few function words and some nouns, instead of every function word
// before the first verb. vocabByTheme() still returns a theme in its own order.
const themeSize = {}, themeIdx = {};
unique.forEach(r => { themeSize[r[5]] = (themeSize[r[5]] || 0) + 1; });

export const VOCAB = unique
  .map(([uk, en, nl, pos, extra, theme]) => {
    themeIdx[theme] = (themeIdx[theme] || 0) + 1;
    return {
      key: `vocab:${uk}`, uk, en, nl, pos, theme,
      rank: (themeIdx[theme] - 1) / themeSize[theme],
      gender: pos === 'n' ? extra : null,
      perfective: pos === 'v' ? extra : null,
    };
  })
  .sort((a, b) => a.rank - b.rank);

export function vocabByTheme(theme) { return VOCAB.filter(w => w.theme === theme); }
